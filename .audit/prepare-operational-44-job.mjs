#!/usr/bin/env node
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const source = resolve(process.argv[3] || '.'), runtimeSha = process.argv[2];
assert.match(runtimeSha || '', /^[0-9a-f]{40}$/);
const root = await mkdtemp(join(tmpdir(), 'isswf-own-factory44-'));
const project = join(root, 'factory-project'), packages = join(root, 'packages'), runsStore = join(root, 'runs');
const run = (exe, args, cwd) => {
  const result = spawnSync(exe, args, { cwd, encoding: 'utf8', timeout: 30000, maxBuffer: 8 * 1024 * 1024 });
  assert.equal(result.status, 0, result.stderr); return result.stdout.trim();
};
const git = (...args) => run('git', ['-C', project, ...args]);
run('git', ['clone', '--quiet', '--local', '--no-hardlinks', source, project]);
git('checkout', '--detach', runtimeSha);
await mkdir(join(project, '.pi'), { recursive: true });
await mkdir(join(project, '.factory/jobs/J802'), { recursive: true });
await writeFile(join(project, '.pi/settings.json'), '{"packages":[],"operatorCustom":{"preserve":true}}\n');
const briefPath = '.factory/jobs/J802/brief.md', checkPath = '.factory/jobs/J802/check.mjs';
const check = `import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
for(const arg of ['--help','help']) {
 const result=spawnSync(process.execPath,['tools/isswf-job.mjs',arg],{encoding:'utf8',timeout:3000});
 assert.equal(result.status,0,'help must succeed without project/config/auth');
 assert.equal(result.stderr,'');
 for(const word of ['run','read','reconcile','--project','--input-sha','--job','--runs-store','--attempt-id','--grant-ref','independent review']) assert.ok(result.stdout.includes(word),'help must explain '+word);
}
const invalid=spawnSync(process.execPath,['tools/isswf-job.mjs','run'],{encoding:'utf8',timeout:3000});
assert.notEqual(invalid.status,0,'help must not bypass run validation');
console.log('3 original operational CLI checks passed');
`;
await writeFile(join(project, checkPath), check);
await writeFile(join(project, briefPath), `# J802: make the normal factory job entry discoverable\n\nThe operator authorized one native LunaHigh implementation attempt on this factory's real CLI. Implement --help and help in tools/isswf-job.mjs. Both must exit0 without project settings, Git pins or auth, list run/read/reconcile and required normal options, and explain that independent review remains required. Keep existing run/read/reconcile validation and behavior. No other writable paths; do not change the protected check or any configuration. Inspect current source, make the smallest change, run node ${checkPath}, and request trusted boundary_check. Use Node or shell only, never Python. No network, Git writes, packages, agents, retries, installs or host tools. Output is a candidate pending independent review, not acceptance.\n`);
const baselinePaths = ['.pi/settings.json', briefPath, checkPath];
git('add', '--', ...baselinePaths);
git('-c', 'user.name=Local factory task', '-c', 'user.email=local@example.invalid', 'commit', '-qm', 'Pin own-factory CLI help task and protected checks');
const targetBase = git('rev-parse', 'HEAD');
const modelsPath = '.factory/models.json';
const modelRead = spawnSync('git', ['-C', project, 'show', `${runtimeSha}:${modelsPath}`], { encoding: 'buffer' });
assert.equal(modelRead.status, 0, modelRead.stderr?.toString());
const actualModels = modelRead.stdout;
const jobPath = '.factory/jobs/J802/job.json';
const job = { version: 1, runtimeSha, targetBase, methodologySha: '37a56ebc902e94f21fc10666f33fceac44946af7', exclusiveAttempt: true, workerTotal: 1, models: { sha: runtimeSha, path: modelsPath, sha256: createHash('sha256').update(actualModels).digest('hex') }, briefPath, referencedInputs: ['tools/isswf-job.mjs', checkPath], expectedMutablePaths: ['tools/isswf-job.mjs'], protectedCheckCommand: `node ${checkPath}` };
await writeFile(join(project, jobPath), JSON.stringify(job, null, 2) + '\n');
git('add', '--', jobPath);
git('-c', 'user.name=Local factory task', '-c', 'user.email=local@example.invalid', 'commit', '-qm', 'Pin normal-entry job configuration');
const inputSha = git('rev-parse', 'HEAD');
const packageTool = join(source, 'tools/factory-package.mjs');
run(process.execPath, [packageTool, 'materialize', '--source', source, '--revision', runtimeSha, '--store', packages]);
const packageRoot = join(packages, runtimeSha);
run(process.execPath, [packageTool, 'activate', '--package', packageRoot, '--project', project]);
const baseline = spawnSync(process.execPath, [checkPath], { cwd: project, encoding: 'utf8', timeout: 5000 });
assert.equal(baseline.status, 1);
assert.match(baseline.stderr, /help must succeed/);
const protectedPaths = [checkPath, briefPath, jobPath, '.pi/settings.json', '.factory/models.json'];
console.log(JSON.stringify({ version: 1, root, source, runtimeSha, project, inputSha, targetBase, jobPath, briefPath, runsStore, attemptId: 'J802-A001', grantRef: 'operator-approved-44-normal-entry-one-native-worker', packageRoot, baselineExit: baseline.status, protectedHashes: Object.fromEntries(await Promise.all(protectedPaths.map(async path => [path, createHash('sha256').update(await readFile(join(project, path))).digest('hex')]))), providerPromptStarted: false, scope: 'Actual own-factory CLI improvement in a disposable factory checkout; no client project or provider until independent precall approval' }, null, 2));
