import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtemp, readFile, access } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createBridge } from './verify-native-coordinator-44.mjs';

const f = JSON.parse(await readFile('.audit/coordinator-exit-44-fixture.json', 'utf8'));
const root = await mkdtemp(join(tmpdir(), 'isswf-coordinator-exit44-negative-'));
const bridge = await createBridge(f, root, 'offline', join(root, 'parent-release'));
const prepared = await bridge.execute({ operation: 'prepare' });
const original = await readFile(join(root, 'worker-task-original.mjs'));
const gated = await readFile(join(root, 'worker-task.mjs'));
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
assert.equal(hash(original), prepared.originalTaskSha256);
assert.equal(hash(gated), prepared.dispatchTaskSha256);
assert.notEqual(prepared.originalTaskSha256, prepared.dispatchTaskSha256);
const body = original.toString('utf8').replace(/^#![^\n]*(?:\n|$)/, '');
assert(gated.toString('utf8').endsWith(body), 'the original body must be unchanged');
assert.equal(hash(gated.toString('utf8').slice(0, -body.length)), prepared.barrierSha256);
await assert.rejects(bridge.execute({ operation: 'prepare' }), /exclusive/);
const run = spawnSync(process.execPath, [join(root, 'worker-task.mjs'), join(root, 'baseline')], { encoding: 'utf8', timeout: 15000, maxBuffer: 1000, env: { PATH: process.env.PATH, HOME: '/nonexistent' } });
assert.equal(run.error, undefined, 'barrier must terminate itself, not require an external timeout');
assert.equal(run.status, 9, 'missing release must fail closed before SDK setup');
assert.equal(run.stdout, ''); assert.equal(run.stderr, '');
for (const path of ['parent-release', 'pi-result.json', 'outside-canary.txt']) assert.equal(await access(join(root, path)).then(() => true, error => { assert.equal(error.code, 'ENOENT'); return false; }), false);
console.log(JSON.stringify({ status: 'PASS', providerPromptStarted: false, root, originalHash: prepared.originalTaskSha256, gatedHash: prepared.dispatchTaskSha256, unchangedOriginalBody: true, missingReleaseExit: run.status, noSdkResultOrCanary: true, duplicatePrepareRefused: true, scope: 'Shared actual task transform and missing-release execution control, no model/coordinator proof.' }));
