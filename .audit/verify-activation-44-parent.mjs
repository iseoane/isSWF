import assert from 'node:assert/strict';
import fs from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { resolve, join } from 'node:path';

const [cliArg, sourceProofArg] = process.argv.slice(2);
assert.ok(cliArg && sourceProofArg, 'Supply the exact CLI path and resource-fixture proof JSON');
const cli = resolve(cliArg);
const sourceProof = JSON.parse(fs.readFileSync(sourceProofArg, 'utf8'));
const invoke = (command, args, cwd) => spawnSync(command, args, { cwd, encoding: 'utf8', timeout: 30000, maxBuffer: 200000 });
const run = args => invoke(process.execPath, [cli, ...args]);
const seed = invoke(process.execPath, ['.audit/prepare-activation-44-fixture.mjs']);
assert.equal(seed.status, 0, seed.stderr);
const fixture = JSON.parse(seed.stdout);
const revision = sourceProof.syntheticCandidateCommit;
const packageRoot = join(fixture.store, revision);
const source = sourceProof.fixtureSource;
const hash = path => createHash('sha256').update(fs.readFileSync(path)).digest('hex');
const initialSettings = fs.readFileSync(join(fixture.project, '.pi/settings.json'));
const checks = [];
let result = run(['materialize', '--source', source, '--revision', revision, '--store', fixture.store]);
assert.equal(result.status, 0, result.stderr);
result = run(['activate', '--package', packageRoot, '--project', fixture.project]);
assert.equal(result.status, 0, result.stderr);
const settingsPath = join(fixture.project, '.pi/settings.json');
const firstBytes = fs.readFileSync(settingsPath);
assert.deepEqual(JSON.parse(firstBytes), { ...JSON.parse(initialSettings), packages: [packageRoot] });
for (const path of ['AGENTS.md', '.factory/models.json', '.factory/jobs/J501/A001.md']) assert.equal(hash(join(fixture.project, path)), fixture.baseline[path]);
result = run(['activate', '--package', packageRoot, '--project', fixture.project]);
assert.equal(result.status, 0, result.stderr);
assert.deepEqual(fs.readFileSync(settingsPath), firstBytes);
checks.push({ name: 'ordinary activation and exact repeat preserve independent seed', passed: true });
const git = args => invoke('git', ['-C', fixture.project, ...args]);
assert.equal(git(['add', '--', '.pi/settings.json']).status, 0);
assert.equal(git(['-c', 'user.name=Factory fixture', '-c', 'user.email=fixture@invalid', '-c', 'commit.gpgsign=false', 'commit', '-qm', 'Record first activation']).status, 0);
const newer = invoke('git', ['-C', source, 'rev-parse', 'HEAD']).stdout.trim();
assert.notEqual(newer, revision);
result = run(['materialize', '--source', source, '--revision', newer, '--store', fixture.store]);
assert.equal(result.status, 0, result.stderr);
result = run(['activate', '--package', join(fixture.store, newer), '--project', fixture.project]);
const secondUnchanged = fs.readFileSync(settingsPath).equals(firstBytes);
const versionReason = /(?:conflict|another|different|already).*(?:factory|version|package)|(?:factory|version|package).*(?:conflict|another|different|already)/iu.test(result.stderr);
checks.push({ name: 'second factory revision refused on clean settings', exit: result.status, unchanged: secondUnchanged, expectedReasonObserved: versionReason, passed: result.status !== 0 && secondUnchanged && versionReason });
const copiedSource = join(fixture.root, 'source-copy');
fs.cpSync(source, copiedSource, { recursive: true });
const alias = join(fixture.root, 'store-alias');
fs.symlinkSync(copiedSource, alias);
result = run(['materialize', '--source', copiedSource, '--revision', revision, '--store', alias]);
const sourceUnchanged = !fs.existsSync(join(copiedSource, revision));
const overlapReason = /(?:separate|overlap|outside)/iu.test(result.stderr);
checks.push({ name: 'store alias into source refused before publication', exit: result.status, sourceUnchanged, expectedReasonObserved: overlapReason, passed: result.status !== 0 && sourceUnchanged && overlapReason });
console.log(JSON.stringify({ result: checks.every(check => check.passed) ? 'PASS' : 'FAIL', cli, cliSha256: hash(cli), sourceFixtureCommit: revision, sourceFixtureNewerCommit: newer, fixture, checks, scope: 'Independent parent regression fixture, exact executable hash and observed outcomes. Synthetic resource commits are not full implementation identity. No provider, trust-catalog, runtime, hostile-filesystem or concurrency proof.' }, null, 2));
if (checks.some(check => !check.passed)) process.exitCode = 1;
